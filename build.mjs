// SYNTHEX static build — no dependencies.
//
//   node build.mjs
//
// Reads src/pages/<lang>/*.html (page bodies with a small front-matter comment),
// wraps them with the shared partials from src/partials, substitutes site-wide
// values from src/site.mjs, and writes finished HTML to the site root (ka) and
// /en (en). Also writes sitemap.xml and robots.txt.
//
// Template syntax (kept deliberately tiny):
//   {{name}}         value from front matter or site config
//   {{root}}         '' on Georgian pages, '../' on English pages
//   {{cur:work}}     becomes ` aria-current="page"` when the page's `active` is "work"

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import site from './src/site.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const langs = ['ka', 'en'];
const read = (p) => readFileSync(p, 'utf8');

const partials = {
  head: read(join(src, 'partials', 'head.html')),
  whatsapp: read(join(src, 'partials', 'whatsapp.html')),
  ka: {
    header: read(join(src, 'partials', 'ka', 'header.html')),
    footer: read(join(src, 'partials', 'ka', 'footer.html')),
  },
  en: {
    header: read(join(src, 'partials', 'en', 'header.html')),
    footer: read(join(src, 'partials', 'en', 'footer.html')),
  },
};

const labels = {
  ka: { whatsapp: 'მოგვწერეთ WhatsApp-ზე', skip: 'გადასვლა შინაარსზე' },
  en: { whatsapp: 'Message us on WhatsApp', skip: 'Skip to content' },
};

// Social links render only for networks that have a URL in site.mjs.
const socialIcons = {
  instagram:
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r="1" fill="currentColor" stroke="none"/></svg>',
  facebook:
    '<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M13.5 21v-7h2.4l.4-3h-2.8V9.1c0-.9.3-1.5 1.5-1.5h1.4V5c-.3 0-1.2-.1-2.2-.1-2.2 0-3.7 1.3-3.7 3.8V11H8v3h2.5v7h3z"/></svg>',
};
const socialNames = { instagram: 'Instagram', facebook: 'Facebook' };
const activeSocial = Object.entries(site.social).filter(([, url]) => url);
// Pill with label (about section, footer)
const socialLinks = activeSocial
  .map(
    ([name, url]) =>
      `<a class="social-link" href="${url}" target="_blank" rel="noopener" aria-label="${socialNames[name]}">${socialIcons[name]}<span>${socialNames[name]}</span></a>`
  )
  .join('\n');
// Icon-only circle (header)
const socialCompact = activeSocial
  .map(
    ([name, url]) =>
      `<a class="social-link social-compact" href="${url}" target="_blank" rel="noopener" aria-label="${socialNames[name]}" title="${socialNames[name]}">${socialIcons[name]}</a>`
  )
  .join('\n');

/** Parse the leading `<!-- key: value -->` block into an object. */
function frontMatter(html) {
  const match = html.match(/^\s*<!--([\s\S]*?)-->/);
  const vars = {};
  if (!match) return { vars, body: html };
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    vars[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return { vars, body: html.slice(match[0].length).trim() };
}

function render(template, vars) {
  return template
    .replace(/\{\{cur:([\w-]+)\}\}/g, (_, name) => (vars.active === name ? ' aria-current="page"' : ''))
    .replace(/\{\{([\w.]+)\}\}/g, (whole, key) => {
      const value = key.split('.').reduce((acc, part) => (acc == null ? undefined : acc[part]), vars);
      if (value === undefined) throw new Error(`Unknown template variable {{${key}}}`);
      return String(value);
    });
}

// --- CSS: one request instead of four. Sources stay separate for editing. ---
const cssOrder = ['tokens', 'base', 'components', 'sections'];
const bundled = cssOrder
  .map((name) => `/* ===== ${name}.css ===== */\n${read(join(here, 'css', `${name}.css`))}`)
  .join('\n');
// Conservative minify: strip comments and collapse whitespace. Strings in
// this codebase contain no significant whitespace, so this is safe.
const minified = bundled
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{}:;,>])\s*/g, '$1')
  .replace(/;}/g, '}')
  .trim();
writeFileSync(join(here, 'css', 'site.css'), `/* GENERATED by build.mjs from css/{tokens,base,components,sections}.css — edit those, not this file. */\n${minified}\n`);
console.log('built css/site.css');

const pages = [];

for (const lang of langs) {
  const dir = join(src, 'pages', lang);
  const root = lang === 'ka' ? '' : '../';
  const outDir = lang === 'ka' ? here : join(here, 'en');
  mkdirSync(outDir, { recursive: true });

  for (const file of readdirSync(dir).filter((f) => f.endsWith('.html'))) {
    const { vars, body } = frontMatter(read(join(dir, file)));
    const slug = file === 'index.html' ? '' : file;
    const pathKa = `/${slug}`;
    const pathEn = file === '404.html' ? '/en/' : `/en/${slug}`;
    const path = lang === 'ka' ? pathKa : pathEn;
    const scripts = ['nav', 'reveal', ...(vars.scripts ? vars.scripts.split(',').map((s) => s.trim()) : [])];
    if (site.gaId) scripts.push('analytics');

    const ctx = {
      ...site,
      ...vars,
      lang,
      root,
      hours: site.hours[lang],
      phoneNbsp: site.phone.replace(/ /g, '&nbsp;'),
      year: new Date().getFullYear(),
      canonical: site.domain + path,
      hreflangKa: site.domain + pathKa,
      hreflangEn: site.domain + pathEn,
      // The 404 page exists only at the root (Netlify serves one 404.html), so its
      // language switch points at the other language's home page instead.
      altLang:
        file === '404.html'
          ? (lang === 'ka' ? 'en/index.html' : '../index.html')
          : (lang === 'ka' ? `${root}en/${file}` : `${root}${file}`),
      ogLocale: lang === 'ka' ? 'ka_GE' : 'en_US',
      ogImageUrl: `${site.domain}/${site.ogImage}`,
      robots: vars.noindex ? 'noindex, nofollow' : 'index, follow',
      gaAttr: site.gaId ? ` data-ga="${site.gaId}"` : '',
      preloadGeorgian:
        lang === 'ka'
          ? `<link rel="preload" href="${root}assets/fonts/noto-georgian.woff2" as="font" type="font/woff2" crossorigin>`
          : '',
      scriptTags: scripts.map((s) => `<script src="${root}js/${s}.js" defer></script>`).join('\n  '),
      whatsappLabel: labels[lang].whatsapp,
      skipLabel: labels[lang].skip,
      socialLinks: socialLinks ? `<div class="social-links">${socialLinks}</div>` : '',
      socialCompact,
    };

    const html = [
      '<!DOCTYPE html>',
      `<html lang="${lang}" class="no-js"${ctx.gaAttr}>`,
      render(partials.head, ctx),
      '<body>',
      `  <a class="skip-link" href="#main">${ctx.skipLabel}</a>`,
      render(partials[lang].header, ctx),
      render(body, ctx),
      render(partials[lang].footer, ctx),
      render(partials.whatsapp, ctx),
      '</body>',
      '</html>',
      '',
    ].join('\n');

    // Drop whitespace-only lines left behind by empty placeholders
    writeFileSync(join(outDir, file), html.replace(/^[ \t]+$/gm, ''));
    if (!vars.noindex) pages.push({ path, lang, pathKa, pathEn });
    console.log(`built ${lang}/${file}`);
  }
}

// --- sitemap.xml with hreflang alternates ---
const urls = pages
  .map(
    (p) => `  <url>
    <loc>${site.domain}${p.path}</loc>
    <xhtml:link rel="alternate" hreflang="ka" href="${site.domain}${p.pathKa}"/>
    <xhtml:link rel="alternate" hreflang="en" href="${site.domain}${p.pathEn}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${site.domain}${p.pathKa}"/>
  </url>`
  )
  .join('\n');
writeFileSync(
  join(here, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls}
</urlset>
`
);

writeFileSync(
  join(here, 'robots.txt'),
  `User-agent: *
Allow: /
Disallow: /src/

Sitemap: ${site.domain}/sitemap.xml
`
);

console.log(`done: ${pages.length} indexable pages, sitemap.xml, robots.txt`);
